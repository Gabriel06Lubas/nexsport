// npm run db:schema: prints nexport's complete schema as one SQL script: the
// migrations in drizzle/ applied in journal order, which is exactly what
// builds the database (tables, enums, exclusion constraints, triggers,
// indexes). Pipe it to a file or into psql on an empty database:
//
//   npm run -s db:schema > schema.sql
//   npm run -s db:schema | psql "$DATABASE_URL" -v ON_ERROR_STOP=1 -1
import { readFileSync } from "node:fs";

const journal = JSON.parse(readFileSync("drizzle/meta/_journal.json", "utf8"));
console.log("-- nexport schema: drizzle migrations 0000–" + journal.entries.at(-1).tag.slice(0, 4) + " in order. Generated by `npm run db:schema`; edit the migrations, not this.\n");
for (const { tag } of journal.entries) {
  const body = readFileSync(`drizzle/${tag}.sql`, "utf8").replaceAll("--> statement-breakpoint", "").trim();
  console.log(`-- ===========================================================================\n-- ${tag}\n-- ===========================================================================\n${body}\n`);
}
